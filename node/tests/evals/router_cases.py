def _halved(cases: list[Case]) -> list[Case]:
    """Even positions within a (lang, group) list tune, odd positions gate."""
    seen: Counter[tuple[str, str]] = Counter()
    out = []
    for c in cases:
        n = seen[(c.lang, c.group)]
        seen[(c.lang, c.group)] += 1
        out.append(replace(c, half="tune" if n % 2 == 0 else "gate"))
    return out


