def _cases() -> list[Case]:
    """Every message in every gated language: TEXTS with SCENARIOS' seeds in the tune half,
    GATE_TEXTS with GATE_SEEDS in the gate half, so every language of a seed shares a half and
    each (language, scenario, half) has ten."""
    out = []
    for lang in GATED_LANGS:
        for scenario, (action, kind, seeds) in SCENARIOS.items():
            halves: tuple[tuple[Literal["tune", "gate"], list[str], list[Seed]], ...] = (
                ("tune", TEXTS[lang][scenario], seeds),
                ("gate", GATE_TEXTS[lang][scenario], GATE_SEEDS[scenario]),
            )
            for half, texts, half_seeds in halves:
                for text, (role, items, missing) in zip(texts, half_seeds, strict=True):
                    out.append(
                        Case(lang, scenario, text, action, role, "", half, kind, items, missing)
                    )
    return out


CASES: list[Case] = _cases()
