def _cases() -> list[Case]:
    """Every message in every gated language. Message n of a scenario is one seed in every
    language, and its half is n's parity (even tune, odd gate), so a seed's languages share a
    half and each (language, scenario) has five of each."""
    out = []
    for lang in GATED_LANGS:
        for scenario, (action, kind, seeds) in SCENARIOS.items():
            texts = TEXTS[lang][scenario]
            for n, (text, (role, items, missing)) in enumerate(zip(texts, seeds, strict=True)):
                half: Literal["tune", "gate"] = "gate" if n % 2 else "tune"
                out.append(Case(lang, scenario, text, action, role, "", half, kind, items, missing))
    return out


CASES: list[Case] = _cases()
