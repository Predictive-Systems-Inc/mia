def _spent() -> list[Case]:
    """Every message of the 19 Oct sets (TEXTS with SCENARIOS' seeds, GATE_TEXTS with
    GATE_SEEDS), half spent: both halves ran, so none is run or scored again."""
    out = []
    for lang in GATED_LANGS:
        for scenario, (action, kind, seeds) in SCENARIOS.items():
            for texts, half_seeds in (
                (TEXTS[lang][scenario], seeds),
                (GATE_TEXTS[lang][scenario], GATE_SEEDS[scenario]),
            ):
                for text, (role, items, missing) in zip(texts, half_seeds, strict=True):
                    out.append(
                        Case(lang, scenario, text, action, role, "", "spent", kind, items, missing)
                    )
    return out


