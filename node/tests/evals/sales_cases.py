def _cases() -> list[Case]:
    """Every message in every gated language; TEXTS tune and GATE_TEXTS gate, so message n of
    a scenario falls in one half in every language. The why answers follow Mia's why question
    in that language."""
    out = []
    for lang in GATED_LANGS:
        for scenario, (action, roles) in SCENARIOS.items():
            previous = t("sales.why", lang) if action == "why_answer" else ""
            for half, texts, items in (
                ("tune", TEXTS[lang][scenario], ITEMS.get(scenario)),
                ("gate", GATE_TEXTS[lang][scenario], GATE_ITEMS.get(scenario)),
            ):
                pairs = items or [[]] * len(texts)
                for text, role, expected in zip(texts, roles, pairs, strict=True):
                    out.append(Case(lang, scenario, text, action, role, expected, previous, half))
    return out


CASES: list[Case] = _cases()
