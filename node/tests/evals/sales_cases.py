def _cases() -> list[Case]:
    """Every message in every gated language; even positions within a (lang, scenario) list
    tune, odd positions gate. The why answers follow Mia's why question in that language."""
    out = []
    for lang in GATED_LANGS:
        for scenario, (action, roles) in SCENARIOS.items():
            texts = TEXTS[lang][scenario]
            items = ITEMS.get(scenario, [[]] * len(texts))
            previous = t("sales.why", lang) if action == "why_answer" else ""
            for n, (text, role, pairs) in enumerate(zip(texts, roles, items, strict=True)):
                half: Literal["tune", "gate"] = "tune" if n % 2 == 0 else "gate"
                out.append(Case(lang, scenario, text, action, role, pairs, previous, half))
    return out


CASES: list[Case] = _cases()
